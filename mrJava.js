let calculoPrimario = Number(prompt("Digite um número"));
let calculoSecundario = Number(prompt("Digite outro número para calcular"));
let resultadoSoma = calculoPrimario + calculoSecundario;
 resultadoMenos = calculoPrimario - calculoSecundario;
 resultadoMulti = calculoPrimario * calculoSecundario;
 resultadoDiv = calculoPrimario / calculoSecundario;

alert(`RESULTADO
    SOMA: ${resultadoSoma} 
    Subtração: ${resultadoMenos} 
    Multiplicação: ${resultadoMulti} 
    Divisão: ${resultadoDiv}`)
       